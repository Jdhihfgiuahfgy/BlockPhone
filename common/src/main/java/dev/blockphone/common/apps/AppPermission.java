package dev.blockphone.common.apps;

import java.util.Locale;

/**
 * Разрешения клиентского приложения — объявляются в app.json ("permissions": [...]) и показываются игроку.
 * Действие, для которого нет разрешения, не загрузится. Доступа к миру, файлам, аккаунтам, мессенджеру, ленте,
 * музыке и Telegram нет ни при каких разрешениях.
 */
public enum AppPermission {
    /** Хранить свои переменные на устройстве (действия "set", "add"; файл blockphone/appdata/&lt;id&gt;.json, до 64 КБ). */
    STORAGE,
    /** Открывать ссылки в браузере (игрок подтверждает каждую). */
    LINKS,
    /** Копировать текст в буфер обмена (только запись, читать буфер нельзя). */
    CLIPBOARD,
    /** Отправлять команды от имени игрока (игрок подтверждает каждую, видит её текст). */
    COMMANDS,
    /** Работать с серверной частью приложения на сервере (переменные и функции). */
    SERVER,
    /** Скрипт: запросы HTTP(S) только к сайтам из "hosts" в app.json (свой сайт, API). Без cookies и данных игрока. */
    INTERNET,
    /** Скрипт: сообщения этому же приложению у других игроков на сервере (сетевые игры) и список игроков с BlockPhone. */
    MULTIPLAYER,
    /**
     * Скрипт: настоящий браузер (Chromium) — любые сайты, вход на них, видео. Cookies — в общем профиле браузера
     * blockphone/browser/profile. Данных телефона (аккаунты, мессенджер, файлы) браузеру не видно.
     */
    BROWSER,
    /**
     * Скрипт: работать в фоне — приложение запускается вместе с игрой и не закрывается при смене мира и сервера
     * (onTick идёт всегда; мессенджеры, напоминания). Рисования без открытого телефона нет.
     */
    BACKGROUND,
    /** Скрипт: уведомления телефона (всплывающее окно и центр уведомлений); нажатие открывает приложение. */
    NOTIFICATIONS,
    /**
     * Скрипт: фото, которые игрок сам выбрал в галерее (photos.pick), — показать и отправить на свой сайт (http.upload);
     * картинки по адресу со своего сайта (gfx.urlImage). Всю галерею приложение не видит.
     */
    PHOTOS,
    /** Скрипт: запись голоса с микрофона (mic.*) — пока идёт запись, телефон показывает значок; голосовые с сайта (audio.*). */
    MICROPHONE,
    /**
     * Скрипт: «режим экрана» — выводить картинку на экран в мире (свой экран игрока или чужой, к которому игрок
     * подключился), управление джойстиком (телефон набок, клавиши и мышь). Видят только те, у кого приложение подключено.
     */
    DISPLAY;

    public String key() {
        return name().toLowerCase(Locale.ROOT);
    }

    public static AppPermission parse(String value) {
        return valueOf(value.strip().toUpperCase(Locale.ROOT));
    }
}
